TEST(ParserTest, InvalidInputsReturnEmptyOptional) {
    EXPECT_FALSE(smallcanon::parse_graph6("").has_value());
    EXPECT_FALSE(smallcanon::parse_graph6("~?").has_value());
    EXPECT_FALSE(smallcanon::parse_graph6("~~??????").has_value());
    EXPECT_FALSE(smallcanon::parse_graph6("D").has_value());
    EXPECT_FALSE(smallcanon::parse_graph6("B\x7f").has_value());
}

TEST(ParserTest, ReadDatasetYieldsOneTuplePerLineWithTrimmedName) {
    std::istringstream input("Ds_   Star5  \n"
                             "Bg\tPath3\n"
                             "@\n");

    struct Entry {
        smallcanon::node_t nodes;
        std::vector<smallcanon::edge_t> edges;
        std::string name;
    };

    std::vector<Entry> entries;
    for (auto&& item: smallcanon::read_dataset(input)) {
        auto& [nodes, edge_generator, name] = item;

        std::vector<smallcanon::edge_t> edges;
        for (const auto& edge: edge_generator) {
            edges.push_back(edge);
        }

        entries.push_back({nodes, edges, std::string{name}});
    }

    ASSERT_EQ(entries.size(), 3);
    EXPECT_EQ(entries[0].nodes, 5);
    EXPECT_EQ(entries[0].edges, (std::vector<smallcanon::edge_t>{{0, 1}, {0, 2}, {0, 3}, {0, 4}}));
    EXPECT_EQ(entries[0].name, "Star5");

    EXPECT_EQ(entries[1].nodes, 3);
    EXPECT_EQ(entries[1].edges, (std::vector<smallcanon::edge_t>{{0, 1}, {1, 2}}));
    EXPECT_EQ(entries[1].name, "Path3");

    EXPECT_EQ(entries[2].nodes, 1);
    EXPECT_TRUE(entries[2].edges.empty());
    EXPECT_TRUE(entries[2].name.empty());
}

TEST(ParserTest, ReadDatasetSkipsInvalidLines) {
    std::istringstream input("D\n"
                             "@ EmptyN1\n");

    std::vector<std::string> names;
    for (auto&& item: smallcanon::read_dataset(input)) {
        auto& [nodes, edge_generator, name] = item;
        (void) edge_generator;

        EXPECT_EQ(nodes, 1);
        names.emplace_back(name);
    }

    ASSERT_EQ(names.size(), 1);
    EXPECT_EQ(names[0], "EmptyN1");
}

TEST(ParserTest, ReadGraphDataSet) {
    const auto dataset_path = std::filesystem::path(SMALLCANON_PROJECT_ROOT) / "datasets" / "paths.g6";
    ASSERT_TRUE(std::filesystem::exists(dataset_path));

    std::ifstream paths_file(dataset_path);
    ASSERT_TRUE(paths_file);

    uint64_t num8 = 0;
    uint64_t num16 = 0;
    uint64_t num32 = 0;
    uint64_t num64 = 0;
    uint64_t num128 = 0;
    uint64_t num_heap = 0;

    for (auto [name, graph]: smallcanon::read_graph_dataset(paths_file)) {
        std::visit(
                [&](auto&& arg) {
                    using T = std::decay_t<decltype(arg)>;
                    if constexpr (std::is_same_v<T, smallcanon::AdjMatrix8>) {
                        num8++;
                    } else if constexpr (std::is_same_v<T, smallcanon::AdjMatrix16>) {
                        num16++;
                    } else if constexpr (std::is_same_v<T, smallcanon::AdjMatrix32>) {
                        num32++;
                    } else if constexpr (std::is_same_v<T, smallcanon::AdjMatrix64>) {
                        num64++;
                    } else if constexpr (std::is_same_v<T, smallcanon::AdjMatrix128>) {
                        num128++;
                    } else if constexpr (std::is_same_v<T, smallcanon::AdjMatrixHeap>) {
                        num_heap++;
                    } else {
                        static_assert(false, "non-exhaustive visitor!");
                    }
                },
                graph);
    }

    ASSERT_EQ(num8, 7);
    ASSERT_EQ(num16, 8);
    ASSERT_EQ(num32, 16);
    ASSERT_EQ(num64, 32);
    ASSERT_EQ(num128, 64);
    ASSERT_EQ(num_heap, 199 - 128);
}
