#include <gtest/gtest.h>
#include <smallcanon/parser.hpp>

#include <string_view>
#include <utility>
#include <vector>

std::tuple<smallcanon::node_t, std::vector<smallcanon::edge_t>, std::string_view>
collect_parsed(std::string_view text) {
    auto [n, gen, rem] = smallcanon::parse_graph6(text);
    std::vector<smallcanon::edge_t> edges;
    for (const smallcanon::edge_t& edge: gen) {
        edges.push_back(edge);
    }
    return {n, edges, rem};
}


#define SC_PARSER_TEST(name, text, nodes, ...)                                                                         \
    TEST(ParserTest, name) {                                                                                           \
        const auto [actual_nodes, actual_edges, remainder] = collect_parsed(text);                                     \
        const std::vector<smallcanon::edge_t> expected_edges = __VA_ARGS__;                                            \
        EXPECT_EQ(actual_nodes, nodes);                                                                                \
        EXPECT_EQ(actual_edges, expected_edges);                                                                       \
        EXPECT_TRUE(remainder.empty());                                                                                \
    }


